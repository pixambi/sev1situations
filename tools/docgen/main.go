// Command docgen writes the Scenarios section of the documentation site from the scenario folders, so the app and the docs
// cannot drift apart (R-SCN-14). With -check it writes nothing and fails if the pages on disk are not what it would write.
package main

import (
	"bytes"
	"flag"
	"fmt"
	"io/fs"
	"os"
	"path"
	"path/filepath"
	"sort"
	"strings"

	"github.com/pixambi/sev1situations/internal/scenario"
)

func main() {
	scenarios := flag.String("scenarios", "scenarios", "the folder holding the scenarios")
	out := flag.String("out", "docs/content/scenarios", "the folder the pages are written to")
	check := flag.Bool("check", false, "fail if the pages on disk are out of date, and write nothing")
	flag.Parse()

	pages, err := generate(os.DirFS(*scenarios))
	if err != nil {
		fmt.Fprintln(os.Stderr, "docgen:", err)
		os.Exit(1)
	}
	if *check {
		stale, err := compare(*out, pages)
		if err != nil {
			fmt.Fprintln(os.Stderr, "docgen:", err)
			os.Exit(1)
		}
		if len(stale) > 0 {
			fmt.Fprintln(os.Stderr, "docgen: the scenario pages are out of date. Run `task docs:generate` and commit the result:")
			for _, s := range stale {
				fmt.Fprintln(os.Stderr, "  "+s)
			}
			os.Exit(1)
		}
		return
	}
	if err := write(*out, pages); err != nil {
		fmt.Fprintln(os.Stderr, "docgen:", err)
		os.Exit(1)
	}
}

// generate returns every page, by path relative to the output folder.
func generate(fsys fs.FS) (map[string][]byte, error) {
	var dirs []string
	err := fs.WalkDir(fsys, ".", func(p string, d fs.DirEntry, err error) error {
		if err != nil {
			return err
		}
		if !d.IsDir() && d.Name() == scenario.FileName {
			dirs = append(dirs, path.Dir(p))
		}
		return nil
	})
	if err != nil {
		return nil, fmt.Errorf("find the scenarios: %w", err)
	}
	sort.Strings(dirs)

	pages := map[string][]byte{"_index.md": []byte(sectionIndex("Scenarios", "Every built-in scenario, by product.", 3))}
	products := map[string]bool{}
	for i, dir := range dirs {
		sc, err := scenario.Load(fsys, dir)
		if err != nil {
			return nil, fmt.Errorf("load %s: %w", dir, err)
		}
		page, err := render(sc, i+1)
		if err != nil {
			return nil, fmt.Errorf("render %s: %w", sc.ID, err)
		}
		if !products[sc.Product] {
			products[sc.Product] = true
			pages[path.Join(sc.Product, "_index.md")] = []byte(sectionIndex(strings.Title(sc.Product), "The "+strings.Title(sc.Product)+" scenarios.", len(products))) //nolint:staticcheck // ASCII product names
		}
		pages[path.Join(sc.Product, sc.ID+".md")] = page
	}
	return pages, nil
}

func sectionIndex(title, desc string, weight int) string {
	return fmt.Sprintf("---\ntitle: %q\ndescription: %q\nweight: %d\n---\n\n<!-- Generated by tools/docgen. Do not edit. -->\n", title, desc, weight)
}

func q(s string) string { return fmt.Sprintf("%q", s) }

// render writes one scenario's page.
func render(sc *scenario.Scenario, weight int) ([]byte, error) {
	var b bytes.Buffer
	w := func(format string, a ...any) { fmt.Fprintf(&b, format, a...) }

	w("---\ntitle: %s\ndescription: %s\nweight: %d\nscenario_id: %s\nproduct: %s\neditions: [%s]\ndifficulty: %s\nminutes: %d\n---\n\n",
		q(sc.Name), q(sc.Summary), weight, q(sc.ID), q(sc.Product), quoteAll(sc.Editions), q(sc.Difficulty), sc.EstimatedMinutes)
	w("<!-- Generated by tools/docgen from the scenario folder. Do not edit. -->\n\n")

	if len(sc.Tags) > 0 {
		w("**Tags:** %s\n\n", "`"+strings.Join(sc.Tags, "`, `")+"`")
	}
	list := func(heading string, items []string) {
		if len(items) == 0 {
			return
		}
		w("## %s\n\n", heading)
		for _, it := range items {
			w("- %s\n", oneLine(it))
		}
		w("\n")
	}
	list("Learning objectives", sc.Objectives)
	list("Prerequisites", sc.Prerequisites)

	if len(sc.Parameters) > 0 {
		w("## Parameters\n\n| Parameter | Type | Default | Notes |\n|---|---|---|---|\n")
		for _, p := range sc.Parameters {
			def := ""
			if p.Default != nil {
				def = fmt.Sprint(p.Default)
			}
			w("| %s | %s | %s | %s |\n", cell(p.Label), p.Type, cell(def), cell(p.Help))
		}
		w("\n")
	}
	text := func(heading, body string) {
		if strings.TrimSpace(body) != "" {
			w("## %s\n\n%s\n\n", heading, oneLine(body))
		}
	}
	text("Initial state", sc.InitialState)
	text("Failure created", sc.FailureCreated)

	if len(sc.Steps) == 0 {
		w("## Steps\n\nThis scenario has no steps. It is an open-ended sandbox, so it runs until you end it.\n\n")
	} else {
		w("## Steps\n\nThe run starts by deploying the scenario, then goes through these steps in order.\n\n")
		for i, st := range sc.Steps {
			w("### %d. %s\n\n*%s step.*%s\n\n", i+1, st.Title, strings.ToUpper(st.Kind[:1])+st.Kind[1:], resetNote(st.ResetPoint))
			guide, err := sc.ReadFile(st.Guide)
			if err != nil {
				return nil, fmt.Errorf("read the guide of step %q: %w", st.ID, err)
			}
			b.WriteString(demote(string(guide), 2))
			b.WriteString("\n")
		}
	}
	text("Success criteria", sc.SuccessCriteria)
	list("Pitfalls", sc.Pitfalls)

	if len(sc.References) > 0 {
		w("## References\n\n")
		for _, r := range sc.References {
			w("- [%s](%s)\n", r.Title, r.URL)
		}
	}
	return b.Bytes(), nil
}

func resetNote(reset bool) string {
	if reset {
		return " You can roll back to the start of this step."
	}
	return ""
}

func quoteAll(in []string) string {
	out := make([]string, len(in))
	for i, s := range in {
		out[i] = q(s)
	}
	return strings.Join(out, ", ")
}

// oneLine joins a folded paragraph's lines, which the YAML may have wrapped.
func oneLine(s string) string { return strings.Join(strings.Fields(s), " ") }

// cell makes text safe inside a table cell.
func cell(s string) string { return strings.ReplaceAll(oneLine(s), "|", `\|`) }

// demote moves every heading of a guide down by n levels, leaving code blocks alone, so a guide's "## Hints" sits under the
// step's heading. Headings deeper than level 6 stay at level 6.
func demote(md string, n int) string {
	var out []string
	fenced := false
	for _, line := range strings.Split(strings.ReplaceAll(md, "\r\n", "\n"), "\n") {
		t := strings.TrimSpace(line)
		if strings.HasPrefix(t, "```") || strings.HasPrefix(t, "~~~") {
			fenced = !fenced
		}
		if !fenced && strings.HasPrefix(line, "#") {
			hashes := len(line) - len(strings.TrimLeft(line, "#"))
			if hashes <= 6 && strings.HasPrefix(line[hashes:], " ") {
				if hashes+n > 6 {
					n = 6 - hashes
				}
				line = strings.Repeat("#", hashes+n) + line[hashes:]
			}
		}
		out = append(out, line)
	}
	return strings.TrimRight(strings.Join(out, "\n"), "\n") + "\n"
}

// write replaces the output folder's generated pages with pages.
func write(dir string, pages map[string][]byte) error {
	if err := os.RemoveAll(dir); err != nil {
		return fmt.Errorf("clear %s: %w", dir, err)
	}
	for rel, content := range pages {
		p := filepath.Join(dir, filepath.FromSlash(rel))
		if err := os.MkdirAll(filepath.Dir(p), 0o755); err != nil {
			return err
		}
		if err := os.WriteFile(p, content, 0o644); err != nil {
			return fmt.Errorf("write %s: %w", p, err)
		}
	}
	return nil
}

// compare lists the pages that are missing, differ or should not be there.
func compare(dir string, pages map[string][]byte) ([]string, error) {
	var stale []string
	have := map[string]bool{}
	err := filepath.WalkDir(dir, func(p string, d fs.DirEntry, err error) error {
		if err != nil {
			if os.IsNotExist(err) {
				return nil
			}
			return err
		}
		if d.IsDir() {
			return nil
		}
		rel, _ := filepath.Rel(dir, p)
		rel = filepath.ToSlash(rel)
		have[rel] = true
		want, ok := pages[rel]
		if !ok {
			stale = append(stale, rel+" should not exist")
			return nil
		}
		got, err := os.ReadFile(p)
		if err != nil {
			return err
		}
		if !bytes.Equal(got, want) {
			stale = append(stale, rel+" differs")
		}
		return nil
	})
	if err != nil {
		return nil, err
	}
	for rel := range pages {
		if !have[rel] {
			stale = append(stale, rel+" is missing")
		}
	}
	sort.Strings(stale)
	return stale, nil
}
